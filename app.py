def get_stress_features(model):
    """Return the exact feature names used by the CatBoost model."""
    if model is None:
        return []

    names = getattr(model, "feature_names_", None)
    if names:
        return list(names)

    names = getattr(model, "feature_names_in_", None)
    if names is not None:
        return list(names)

    return []


