def normalize_name(value):
    """
    Makes names comparable across:
        GPA
        gpa
        Semester GPA
        Semester_GPA
        semester-gpa
    """
    return (
        str(value)
        .strip()
        .lower()
        .replace("_", "")
        .replace(" ", "")
        .replace("-", "")
    )


def raw_student_dataframe(student):
    """
    Canonical raw feature names.

    Match the training dataset's representation: binary fields are numeric,
    while Department and Parental_Education remain CatBoost categorical data.
    """
    return pd.DataFrame(
        [
            {
                "Age": student["age"],
                "Gender": binary_value(student["gender"], "Gender"),
                "Department": student["department"],
                "Year of study": student["year_of_study"],
                "GPA": student["gpa"],
                "Semester_GPA": student["semester_gpa"],
                "CGPA": student["cgpa"],
                "Attendance_Rate": student["attendance_rate"],
                "Study_Hours_per_Day": student["study_hours_per_day"],
                "Assignment_Delay_Days": student["assignment_delay_days"],
                "Travel_Time_Minutes": student["travel_time_minutes"],
                "Family_Income": student["family_income"],
                "Scholarship": binary_value(
                    student["scholarship"], "Scholarship"
                ),
                "Part_Time_Job": binary_value(
                    student["part_time_job"], "Part_Time_Job"
                ),
                "Internet_Access": binary_value(
                    student["internet_access"], "Internet_Access"
                ),
                "Parental_Education": student["parental_education"],
            }
        ]
    )


def binary_value(value, field_name):
    """Convert form labels to the 0/1 values used by the training data."""
    normalized = str(value).strip().lower()

    if field_name == "Gender":
        values = {"female": 0, "male": 1}
    else:
        values = {"no": 0, "yes": 1}

    if normalized not in values:
        raise ValueError(
            f"Unsupported {field_name} value: {value!r}. "
            f"Expected one of {sorted(values)}."
        )

    return values[normalized]


def find_raw_column(raw_columns, requested):
    """Find a raw column by normalized name."""
    requested_norm = normalize_name(requested)

    for column in raw_columns:
        if normalize_name(column) == requested_norm:
            return column

    return None


def build_catboost_input(student, required_features):
    """
    CatBoost normally expects the same raw feature columns used during
    training, especially when categorical features were used.

    We therefore do NOT one-hot encode CatBoost inputs here.
    """
    raw = raw_student_dataframe(student)

    missing = []
    columns = {}

    for feature in required_features:
        match = find_raw_column(raw.columns, feature)

        if match is None:
            missing.append(feature)
        else:
            columns[feature] = raw[match].iloc[0]

    if missing:
        raise ValueError(
            "The CatBoost model expects feature(s) that are not present "
            f"in the application input: {missing}"
        )

    return pd.DataFrame([columns], columns=required_features)


def one_hot_value(raw_value, category):
    """
    Match values such as:
        Data Science
        Data_Science
        data-science
    """
    return normalize_name(raw_value) == normalize_name(category)


def build_xgboost_input(student, stress_index, required_features):
    """
    Build the exact column order stored in the XGBoost metadata.

    Supports:
      - direct numeric/raw columns
      - normalized column-name matching
      - one-hot columns such as Gender_Female
      - predicted Stress_Index
    """
    raw = raw_student_dataframe(student)
    raw["Stress_Index"] = float(stress_index)

    result = pd.DataFrame(index=[0])
    missing = []

    for feature in required_features:

        # 1. Direct/normalized raw column
        match = find_raw_column(raw.columns, feature)

        if match is not None:
            result[feature] = [raw[match].iloc[0]]
            continue

        # 2. Predicted stress is already in raw
        if normalize_name(feature) == normalize_name("Stress_Index"):
            result[feature] = [float(stress_index)]
            continue

        # 3. One-hot encoded feature
        #    Examples:
        #       Gender_Female
        #       Department_Data Science
        #       Scholarship_Yes
        #       Parental_Education_Primary
        if "_" in str(feature):
            prefix, category = str(feature).split("_", 1)

            base_column = find_raw_column(raw.columns, prefix)

            if base_column is not None:
                raw_value = raw[base_column].iloc[0]

                result[feature] = [
                    1 if one_hot_value(raw_value, category) else 0
                ]
                continue

        # Do not silently invent a value for an unknown feature.
        missing.append(feature)

    if missing:
        raise ValueError(
            "The XGBoost model expects feature(s) that could not be "
            f"constructed from the form: {missing}"
        )

    return result[required_features]


# ============================================================
# MODEL PREDICTION
# ============================================================

def predict_stress(student):
    if stress_model is None:
        raise FileNotFoundError(
            f"Stress model not found: {STRESS_MODEL_PATH}"
        )

    if not stress_features:
        raise ValueError(
            "The CatBoost model does not expose its feature names. "
            "The exact feature list used during training is required."
        )

    # A future dropout outcome cannot be known at assessment time.
    forbidden = {
        normalize_name("Dropout"),
        normalize_name("Stress_Index"),
        normalize_name("Stress"),
        normalize_name("Stress_Index_Target"),
    }

    invalid_features = [
        feature
        for feature in stress_features
        if normalize_name(feature) in forbidden
    ]

    if invalid_features:
        raise ValueError(
            "The CatBoost stress model contains target/leakage feature(s): "
            f"{invalid_features}. Retrain the stress model without "
            "future outcome variables."
        )

    X = build_catboost_input(student, stress_features)

    prediction = stress_model.predict(X)
    stress_value = float(np.asarray(prediction).reshape(-1)[0])

    if not np.isfinite(stress_value):
        raise ValueError("The stress model returned an invalid value.")

    return stress_value


def predict_dropout(student, stress_index):
    if dropout_model is None:
        raise FileNotFoundError(
            f"Dropout model not found: {DROPOUT_MODEL_PATH}"
        )

    if not dropout_features:
        raise ValueError(
            "No dropout feature list was found in the metadata JSON."
        )

    # The target must never be an input feature.
    target_name = normalize_name(
        dropout_meta.get("target", "Dropout")
    )

    leakage_features = [
        feature
        for feature in dropout_features
        if normalize_name(feature) == target_name
        or normalize_name(feature) == normalize_name("Dropout")
    ]

    if leakage_features:
        raise ValueError(
            "TARGET LEAKAGE DETECTED: the XGBoost input feature list "
            f"contains the target column {leakage_features}. "
            "Remove Dropout from X before retraining the model."
        )

    X = build_xgboost_input(
        student,
        stress_index,
        dropout_features,
    )

    if not hasattr(dropout_model, "predict_proba"):
        raise ValueError(
            "The loaded dropout model does not provide predict_proba()."
        )

    probabilities = dropout_model.predict_proba(X)

    if probabilities.ndim != 2 or probabilities.shape[1] < 2:
        raise ValueError(
            "The dropout model does not appear to be a binary "
            "classification model."
        )

    probability = float(probabilities[0, 1])

    if not 0.0 <= probability <= 1.0:
        raise ValueError("The dropout probability is outside [0, 1].")

    return probability


# ============================================================
# RISK CLASSIFICATION
# ============================================================

def get_risk_level(probability):
    if probability >= MEDIUM_HIGH_CUTOFF:
        return "High"

    if probability >= LOW_MEDIUM_CUTOFF:
        return "Medium"

    return "Low"


