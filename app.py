@st.cache_resource
def load_stress_model():
    if not STRESS_MODEL_PATH.exists():
        return None
    return joblib.load(STRESS_MODEL_PATH)


@st.cache_resource
def load_dropout_artifacts():
    if not DROPOUT_MODEL_PATH.exists():
        return None, None

    if not DROPOUT_META_PATH.exists():
        return None, None

    with open(DROPOUT_MODEL_PATH, "rb") as f:
        model = pickle.load(f)

    with open(DROPOUT_META_PATH, "r", encoding="utf-8") as f:
        meta = json.load(f)

    return model, meta


